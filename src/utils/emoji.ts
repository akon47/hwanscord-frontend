export const ALL_EMOJI: EmojiEntry[] = EMOJI_CATEGORIES.flatMap((c) => c.emojis)

const BY_NAME = new Map(ALL_EMOJI.map((em) => [em.name, em]))

export function emojiByName(name: string): EmojiEntry | undefined {
  return BY_NAME.get(name)
}

export function searchEmoji(query: string, limit = 50): EmojiEntry[] {
  const q = query.trim().toLowerCase()
  if (!q) return ALL_EMOJI.slice(0, limit)
  const starts: EmojiEntry[] = []
  const contains: EmojiEntry[] = []
  for (const em of ALL_EMOJI) {
    const haystack = [em.name, ...em.keywords]
    if (haystack.some((k) => k.toLowerCase().startsWith(q))) starts.push(em)
    else if (haystack.some((k) => k.toLowerCase().includes(q))) contains.push(em)
    if (starts.length >= limit) break
  }
  return [...starts, ...contains].slice(0, limit)
}

