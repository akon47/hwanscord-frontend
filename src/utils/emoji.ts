const EMOJI_ONLY_RE = /^(?:\p{Extended_Pictographic}(?:️|‍\p{Extended_Pictographic})*|\p{Regional_Indicator}{2})(?:\s*(?:\p{Extended_Pictographic}(?:️|‍\p{Extended_Pictographic})*|\p{Regional_Indicator}{2}))*$/u

/** Messages made only of a few emoji render larger (like Discord's jumbo emoji). */
export function isEmojiOnly(content: string, maxCount = 10): boolean {
  const trimmed = content.trim()
  if (!trimmed || !EMOJI_ONLY_RE.test(trimmed)) return false
  const count = [...new Intl.Segmenter(undefined, { granularity: 'grapheme' }).segment(trimmed)].filter(
    (s) => s.segment.trim(),
  ).length
  return count <= maxCount
}
